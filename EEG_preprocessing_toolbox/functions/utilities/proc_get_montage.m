function [montage, labels] = proc_get_montage(type)
% [montage, labels] = proc_get_montage(type)
%
% The function retrieves standard montage layouts. Type argument represents
% the kind of layout you want to retrieve. Type argument has the following 
% format: 'DATATYPE.DEVICE.NCHANNELS.[CONFIG]' (e.g., 'eeg.gtec.16.smr').
% Montage is a two dimensional matrix with the indexes of channels and 
% zero padding for empty elements. Optional output labels is a cell array
% with the channels labels.
% 
% The following layout are currently implemented:
%
%   'eeg.biosemi.64'            Biosemi 64 EEG channel layout
%   'exg.biosemi.8'             Biosemi 8 EXG channels
%   'eeg.gtec.16.smr'           gTec 16 EEG channel layout in smr
%                               configuration
%   'eeg.gtec.16.eog.smr'       gTec 16 EEG channel layout in smr
%                               configuration without eog electrodes (12
%                               and 16)
%   'eeg.acticamp.16.cvsa'      actiCAmp 16 EEG channel layout in cvsa
%                               configuration
%   'eeg.acticamp.63.cvsa'      actiCAmp 63 EEG channel layout in cvsa
%                               configuration
%   'eeg.inria.32.cvsa'         Inria 32 EEG channel layout in cvsa
%                               configuration (probably 2 gUSBamps)
%   'eeg.gtec.16.cvsa'          gTec 16 EEG channel layout in cvsa
%                               configuration
%   'eeg.antneuro.32.mi'        antneuro 32 EEG channel layout in mi
%                               configuration (64 channel cap) [bochum]
%   'eeg.antneuro.64.mi'        antneuro 64 EEG channel layout in mi
%                               configuration (64 channel cap) [bochum]
%   'eeg.quick20.19.mi'         Quick-20 19 EEG channel layout in mi
%                               configuration 
%   'eeg.gtec.nautilus.62'         gTec Nautilus 62 EEG channel layout
%
% SEE ALSO: proc_laplacian_mask, proc_laplacian

    switch lower(type)
        case 'eeg.biosemi.64'
            [montage, labels] = layout_eeg_biosemi_64;
        case 'exg.biosemi.8'
            [montage, labels] = layout_exg_biosemi_8;
        case 'erg.biosemi.16'
            [montage, labels] = layout_erg_biosemi_16;
        case 'eeg.gtec.16.smr'
            [montage, labels] = layout_eeg_gtec_16_smr;
        case 'eeg.gtec.16.eog.smr'
            [montage, labels] = layout_eeg_gtec_16_eog_smr;
        case 'eeg.acticamp.16.cvsa'
            [montage, labels] = layout_eeg_acticamp_16_cvsa;
        case 'eeg.acticamp.63.cvsa'
            [montage, labels] = layout_eeg_acticamp_63_cvsa;
        case 'eeg.inria.32.cvsa'
            [montage, labels] = layout_eeg_inria_32_cvsa;
        case 'eeg.gtec.16.cvsa'
            [montage, labels] = layout_eeg_gtec_16_cvsa;
        case 'eeg.antneuro.32.mi'
            [montage, labels] = layout_eeg_antneuro_32_mi;
        case 'eeg.antneuro.64.mi'
            [montage, labels] = layout_eeg_antneuro_64_mi;
        case 'eeg.quick20.19.mi'
            [montage, labels] = layout_eeg_quick20_19_mi;
        case 'eeg.gtec.nautilus.62'
            [montage, labels] = layout_eeg_gtec_62;
        otherwise
            error('chk:typ', ['[' mfilename '] Unknown montage type requested (probably not yet implemented']);
    end
end

